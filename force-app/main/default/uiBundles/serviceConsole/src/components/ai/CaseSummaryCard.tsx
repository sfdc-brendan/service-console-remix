import { useCallback } from 'react';
import { RefreshCw, ShieldAlert, Sparkles } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { consoleApi } from '@/api/console/consoleApi';
import { useResource } from '@/hooks/useResource';
import { relativeTime } from '@/lib/format';
import { cn } from '@/lib/utils';
import {
  AiTag,
  ErrorNote,
  Panel,
  SentimentBadge,
  ShimmerLines,
} from '@/components/console/primitives';

const RISK_CLASS = {
  low: 'bg-positive/12 text-positive',
  medium: 'bg-warning/20 text-foreground',
  high: 'bg-negative/12 text-negative',
} as const;

export function CaseSummaryCard({
  caseId,
  className,
}: {
  caseId: string;
  className?: string;
}) {
  const summary = useResource(
    useCallback(() => consoleApi.caseSummary(caseId), [caseId]),
    caseId
  );
  const data = summary.data;

  return (
    <Panel
      title="Case summary"
      icon={Sparkles}
      tone="ai"
      className={className}
      action={
        <Button
          variant="ghost"
          size="icon"
          onClick={() => void summary.refresh()}
          disabled={summary.loading}
          aria-label="Regenerate summary"
        >
          <RefreshCw
            className={cn('size-3.5', summary.loading && 'animate-spin')}
            aria-hidden="true"
          />
        </Button>
      }
    >
      {summary.error ? (
        <ErrorNote
          message={summary.error}
          onRetry={() => void summary.refresh()}
        />
      ) : !data ? (
        <ShimmerLines lines={5} />
      ) : (
        <div className="space-y-3">
          <p className="font-display text-lg leading-snug font-semibold">
            {data.headline}
          </p>
          <p className="text-sm leading-relaxed text-foreground/85">
            {data.summary}
          </p>
          {data.keyPoints.length ? (
            <ul className="grid gap-1.5 sm:grid-cols-2">
              {data.keyPoints.map(point => (
                <li
                  key={point}
                  className="flex gap-2 rounded-lg bg-white/70 px-2.5 py-1.5 text-xs"
                >
                  <span
                    className="mt-1 size-1.5 shrink-0 rounded-full bg-ai"
                    aria-hidden="true"
                  />
                  {point}
                </li>
              ))}
            </ul>
          ) : null}
          <div className="flex flex-wrap items-center gap-x-4 gap-y-2 border-t border-ai/15 pt-3 text-xs">
            <span className="flex items-center gap-1.5">
              <SentimentBadge sentiment={data.sentiment} />
              <span className="text-muted-foreground">
                {data.sentimentReason}
              </span>
            </span>
            <span
              className={cn(
                'inline-flex items-center gap-1 rounded-full px-2 py-0.5 font-semibold capitalize',
                RISK_CLASS[data.risk]
              )}
            >
              <ShieldAlert className="size-3" aria-hidden="true" /> {data.risk}{' '}
              risk
            </span>
            <span className="text-muted-foreground">{data.riskReason}</span>
          </div>
          {data.customerContext ? (
            <p className="text-xs text-muted-foreground italic">
              {data.customerContext}
            </p>
          ) : null}
          <div className="flex items-center justify-between">
            <AiTag label="Generated by Agentforce" />
            <span className="text-[11px] text-muted-foreground">
              {relativeTime(data.generatedAt)}
            </span>
          </div>
        </div>
      )}
    </Panel>
  );
}
